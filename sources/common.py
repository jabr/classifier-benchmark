"""Shared plumbing for source-sample generation.

A Source turns external dataset records into (state, label) candidates; the
generator dedupes, filters, redacts, and draws a deterministic balanced sample
with a 16-bit seed (the sample id suffix is the seed in hex), then writes the
suite TOML with a provenance header.
"""

import json
import random
import re
import sys
import tomllib
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from bench.cases import Case, Choice, Task, load_suite

SOURCES_DIR = Path(__file__).resolve().parent
SAMPLES_DIR = SOURCES_DIR / "samples"
CACHE_DIR = SOURCES_DIR / ".cache"

EMAIL_RE = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
PHONE_RE = re.compile(r"(?:\+?1[-. ]?)?\(?\d{3}\)?[-. ]\d{3}[-. ]\d{4}")

DATASETS_SERVER = "https://datasets-server.huggingface.co"


@dataclass
class Source:
  name: str
  dataset_id: str
  split: str
  static: bool
  question: dict
  loader: object
  type: str = "choice"          # choice | noul | score
  label_map: dict | None = None  # raw label -> expected (bool/int), when the
                                 # dataset axis differs from the wire answer


def redact(text: str) -> str:
  text = EMAIL_RE.sub("[EMAIL]", text)
  text = PHONE_RE.sub("[PHONE]", text)
  return text


def ds_server_rows(repo_id: str, split: str, pool: int, config: str = "default") -> list[dict]:
  """Rows straight from HF's datasets-server REST API (no file downloads).

  Sources only ever sample a subset, so this avoids hauling multi-hundred-MB
  parquet files for a few thousand rows. 100 rows per page, iterated in file
  order until `pool` rows are collected.
  """
  import urllib.parse
  from urllib.request import urlopen

  rows = []
  offset = 0
  while len(rows) < pool:
    url = f"{DATASETS_SERVER}/rows?dataset={urllib.parse.quote(repo_id, safe='')}&config={config}&split={split}&offset={offset}&length=100"
    with urlopen(url, timeout=60) as resp:
      page = json.load(resp)
    page_rows = page.get("rows", [])
    if not page_rows:
      break
    rows.extend(item["row"] for item in page_rows)
    offset += len(page_rows)
  return rows[:pool]


def hf_rows(repo_id: str, filename: str, pool: int) -> list[dict]:
  """Rows from one data file on the Hub (JSONL or parquet), read incrementally."""
  import json as _json

  from huggingface_hub import hf_hub_download

  path = hf_hub_download(repo_id, filename, repo_type="dataset")
  if filename.endswith(".parquet"):
    import pyarrow.parquet as pq

    reader = pq.ParquetFile(path)
    rows = []
    for batch in reader.iter_batches(batch_size=256):
      columns = {name: batch.column(name).to_pylist() for name in batch.schema.names}
      for i in range(batch.num_rows):
        rows.append({name: col[i] for name, col in columns.items()})
        if len(rows) >= pool:
          return rows
    return rows
  rows = []
  with open(path, encoding="utf-8") as fh:
    for line in fh:
      if line.strip():
        rows.append(_json.loads(line))
      if len(rows) >= pool:
        break
  return rows


def balanced_pick(rng: random.Random, items: list[tuple[str, str]], n: int) -> list[tuple[str, str]]:
  """Deterministic stratified sample: equal per class, leftovers in RNG order."""
  classes: dict[str, list] = {}
  for item in items:
    classes.setdefault(item[1], []).append(item)
  order = sorted(classes)
  rng.shuffle(order)
  picked = []
  quota, extra = divmod(n, len(order))
  for i, label in enumerate(order):
    pool = sorted(classes[label])
    rng.shuffle(pool)
    taken = pool[: quota + (1 if i < extra else 0)]
    picked.extend(taken)
  rng.shuffle(picked)
  return picked


def prepare_candidates(rows: list[tuple[str, str]], source: Source, args) -> list[tuple[str, str]]:
  seen = set()
  items = []
  for text, label in rows:
    text = (text or "").strip()
    if not text or text in seen:
      continue
    seen.add(text)
    if not args.no_redact:
      text = redact(text)
    words = len(text.split())
    if not args.min_words <= words <= args.max_words:
      continue
    items.append((text, label))
  return items


def toml_str(value: str) -> str:
  return json.dumps(value, ensure_ascii=False)


def emit_sample(path: Path, source: Source, seed: int, task: Task, meta: dict) -> None:
  from bench.cases import Choice, Noul, Score

  q = task.question
  lines = [
    "# Real-data sample suite (generated by sources/generate.py)",
    f"# source: {source.dataset_id} split={source.split}",
    f"# generated: {datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}",
    f"# seed: {seed} (sample id suffix: {seed & 0xffff:04x})",
    f"# candidates scraped: {meta['pool']}; after dedupe/filters: {meta['usable']}",
    f"# filters: {meta['min_words']} <= words <= {meta['max_words']}; email/phone redaction: "
    f"{'off' if meta['no_redact'] else 'on [EMAIL]/[PHONE]'}",
    "# class counts: " + " ".join(f"{k}={v}" for k, v in sorted(meta["counts"].items())) + f" (requested {meta['n']})",
    "# The sample file is the stable artifact; the seed only reproduces a selection",
    "# over the source snapshot that existed at generation time.",
    "",
    "[[task]]",
    f"id = {toml_str(task.id)}",
    f'type = "{source.type}"',
    "",
    "[task.question]",
    f"instructions = {toml_str(q.instructions)}",
  ]
  if isinstance(q, Choice):
    lines += ["", "[task.question.criteria]"]
    lines += [f"{key} = {toml_str(desc)}" for key, desc in q.criteria.items()]
  elif isinstance(q, Noul):
    if q.criteria is not None:
      lines += ["", "[task.question.criteria]"]
      lines += [f"{key} = {toml_str(desc)}" for key, desc in q.criteria.items()]
  else:
    assert isinstance(q, Score)
    lines += ["", f"criteria = {toml_str(list(q.criteria))}"]
  for case in task.cases:
    lines += [
      "",
      "[[task.cases]]",
      f"state = {toml_str(case.state)}",
      f"expected = {toml_str(case.expected)}",
    ]
  path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def generate(source: Source, args) -> Path:
  from bench.cases import Choice, Noul, Score

  rows = source.loader(args.pool)
  items = prepare_candidates(rows, source, args)
  if source.label_map is not None:
    try:
      items = [(text, source.label_map[label]) for text, label in items]
    except KeyError as e:
      raise SystemExit(f"{source.name}: label {e} not in label_map") from e
  if len(items) < args.n:
    raise SystemExit(
      f"{source.name}: only {len(items)} usable candidates after filters, want {args.n} "
      "(raise --pool, widen word bounds, or lower --n)"
    )
  rng = random.Random(f"{source.name}:{args.seed}")
  picked = balanced_pick(rng, items, args.n)
  if len(picked) < args.n:
    print(
      f"warning: {source.name}: requested {args.n} balanced cases but some classes ran short "
      f"({len(picked)} sampled); class counts are in the file header",
      file=sys.stderr,
    )
  suffix = f"{args.seed & 0xffff:04x}"
  if source.type == "choice":
    question = Choice(instructions=source.question["instructions"], criteria=dict(source.question["criteria"]))
  elif source.type == "noul":
    question = Noul(
      instructions=source.question["instructions"],
      criteria=dict(source.question["criteria"]) if source.question.get("criteria") else None,
    )
  else:
    question = Score(instructions=source.question["instructions"], criteria=list(source.question["criteria"]))
  task = Task(
    id=f"{source.name}_{suffix}",
    type=source.type,
    question=question,
    cases=[Case(state=text, expected=label) for text, label in picked],
  )
  SAMPLES_DIR.mkdir(parents=True, exist_ok=True)
  path = SAMPLES_DIR / f"{source.name}-{suffix}.toml"
  if path.exists() and not args.force:
    raise SystemExit(f"{path} already exists (use --force to overwrite)")
  class_counts = {}
  for _, label in picked:
    class_counts[label] = class_counts.get(label, 0) + 1
  emit_sample(
    path, source, args.seed, task,
    {"pool": len(rows), "usable": len(items), "counts": class_counts,
     "n": args.n, "min_words": args.min_words, "max_words": args.max_words,
     "no_redact": args.no_redact},
  )
  # round-trip: the generated file must load through the bench-owned loader
  check = load_suite(path)
  assert check[0].id == task.id and len(check[0].cases) == len(picked)
  return path
